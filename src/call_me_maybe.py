"""Program entry point."""

from pathlib import Path
from llm_sdk import Small_LLM_Model
from loaders import load_function_definitions, load_test_cases
from constrained_decoder import generate_constrained, get_function_names


def main() -> None:
    """Load and display project data."""
    functions = load_function_definitions(
        Path("functions_definition.json")
    )
    test_cases = load_test_cases(
        Path("function_calling_tests.json")
    )

    print("Functions:")
    for function in functions:
        print(function)

    print("\nTest cases:")
    for test_case in test_cases:
        print(test_case)


    function_names: list[str] = get_function_names(functions)
    print(f"Function names: {function_names}")

    llm = Small_LLM_Model(device='cpu')
    generated_name = generate_constrained(llm, "fn", function_names)
    print(f"Name generated by the LLM: {generated_name}")


if __name__ == "__main__":
    main()
