"""Program entry point."""

from pathlib import Path
from llm_sdk import Small_LLM_Model
from loaders import load_function_definitions, load_test_cases
from constrained_decoder import generate_constrained, get_function_names


def main() -> None:
    """Load and display project data."""
    functions = load_function_definitions(
        Path("functions_definition.json")
    )
    test_cases = load_test_cases(
        Path("function_calling_tests.json")
    )
    function_names = get_function_names(functions)

    llm = Small_LLM_Model(device='cpu')
    initial_text = "generated function: "
    initial_batch = llm.encode(initial_text)
    initial_tokens = initial_batch.tolist()[0]
    target_texts = [initial_text + text for text in function_names]
    generated_name, token_ids = generate_constrained(
        llm,
        initial_text,
        initial_tokens,
        target_texts
    )
    print(f"Name generated by the LLM: {generated_name}")
    print(f"Tokens used: {token_ids}")


if __name__ == "__main__":
    main()
