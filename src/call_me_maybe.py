"""Program entry point."""

from pathlib import Path
from llm_sdk import Small_LLM_Model
from models import FunctionDefinition
from loaders import load_function_definitions, load_test_cases
from constrained_decoder import (
    generate_constrained,
    get_function_names,
    get_function_definition
)


def main() -> None:
    """Load and display project data."""
    functions = load_function_definitions(
        Path("functions_definition.json")
    )
    test_cases = load_test_cases(
        Path("function_calling_tests.json")
    )
    function_names = get_function_names(functions)

    llm = Small_LLM_Model(device='cpu')
    generated_json = '{"function": "'
    initial_batch = llm.encode(generated_json)
    token_ids = initial_batch.tolist()[0]

    target_texts = [generated_json + text for text in function_names]
    generated_json, token_ids = generate_constrained(
        llm,
        generated_json,
        token_ids,
        target_texts
    )
    try:
        function: FunctionDefinition = get_function_definition(
            functions,
            generated_json
        )
        print(f"Function found: {function.name}")
    except ValueError as e:
        print(f"Error: {e}")

    target_texts = [generated_json + '"}']
    generated_json, token_ids = generate_constrained(
        llm,
        generated_json,
        token_ids,
        target_texts
    )

    print(f"JSON generated by the LLM: {generated_json}")
    print(f"Tokens used: {token_ids}")


if __name__ == "__main__":
    main()
